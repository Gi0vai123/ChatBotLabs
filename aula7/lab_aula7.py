    # TODO 3.5: Escreva a condicional if/else abaixo

    if maior_confianca < threshold or intencao_prevista == "fora_escopo":
        return {
            "status": "fallback",
            "mensagem": "Solicitação fora do escopo."
        }
    else:
        return {
            "status": "sucesso",
            "intencao": intencao_prevista,
            "confianca": round(maior_confianca, 2),
            "codigo_rastreio": extrair_codigo_rastreio(mensagem_usuario)
        }

